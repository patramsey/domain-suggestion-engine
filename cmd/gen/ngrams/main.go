// Generates internal/scorer/ngrams_gen.go from an English word corpus.
// Computes character bigram log-probabilities (Laplace-smoothed) and
// score-range constants for normalising the brandability signal.
//
// Data source: dwyl/english-words words_alpha.txt (~370K lowercase alpha words)
// Usage: go run ./cmd/gen/ngrams
package main

import (
	"bufio"
	"fmt"
	"math"
	"net/http"
	"os"
	"sort"
	"strings"
	"text/template"
	"time"
)

const (
	wordsURL    = "https://raw.githubusercontent.com/dwyl/english-words/master/words_alpha.txt"
	outPath     = "internal/scorer/ngrams_gen.go"
	httpTimeout = 30 * time.Second
)

func main() {
	words, err := fetchWords()
	if err != nil {
		fmt.Fprintf(os.Stderr, "fetch words: %v\n", err)
		os.Exit(1)
	}
	fmt.Printf("Loaded %d words\n", len(words))

	logProbs, min5, max95 := buildModel(words)
	fmt.Printf("Score range (5th–95th pct): %.4f – %.4f\n", min5, max95)

	if err := writeGenFile(outPath, logProbs, min5, max95, len(words)); err != nil {
		fmt.Fprintf(os.Stderr, "write: %v\n", err)
		os.Exit(1)
	}
	fmt.Printf("Wrote %s\n", outPath)
}

func fetchWords() ([]string, error) {
	client := &http.Client{Timeout: httpTimeout}
	resp, err := client.Get(wordsURL)
	if err != nil {
		return nil, fmt.Errorf("GET: %w", err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("HTTP %d", resp.StatusCode)
	}

	var words []string
	scanner := bufio.NewScanner(resp.Body)
	for scanner.Scan() {
		w := strings.TrimSpace(strings.ToLower(scanner.Text()))
		if len(w) >= 2 && len(w) <= 20 && isAlpha(w) {
			words = append(words, w)
		}
	}
	return words, scanner.Err()
}

func isAlpha(s string) bool {
	for _, r := range s {
		if r < 'a' || r > 'z' {
			return false
		}
	}
	return true
}

// buildModel computes Laplace-smoothed bigram log-probabilities and returns the
// 5th and 95th percentile of per-word average log-prob for normalisation.
func buildModel(words []string) (logProbs [26][26]float64, min5, max95 float64) {
	var counts [26][26]int
	var rowTotals [26]int

	for _, w := range words {
		for i := 0; i < len(w)-1; i++ {
			a, b := w[i]-'a', w[i+1]-'a'
			counts[a][b]++
			rowTotals[a]++
		}
	}

	// Laplace smoothing: add 1 to every bigram count, add 26 to row total
	for i := 0; i < 26; i++ {
		denom := float64(rowTotals[i] + 26)
		for j := 0; j < 26; j++ {
			logProbs[i][j] = math.Log(float64(counts[i][j]+1) / denom)
		}
	}

	// Score every word to find the normalization range
	scores := make([]float64, 0, len(words))
	for _, w := range words {
		if s, ok := scoreWord(w, logProbs); ok {
			scores = append(scores, s)
		}
	}
	sort.Float64s(scores)
	n := len(scores)
	if n == 0 {
		return logProbs, -5, -1
	}
	p5 := scores[n*5/100]
	max95 = scores[n*95/100]

	// Extend the min anchor one full inter-percentile range below p5 so that:
	//   - most English words map to [0.4, 1.0]
	//   - words with unusual bigrams (doubled letters, rare clusters) stay ≥ 0.3
	//   - truly random strings score below 0.2 (clamped to 0.1)
	min5 = p5 - (max95 - p5)
	return logProbs, min5, max95
}

// scoreWord returns the average bigram log-prob for a word.
func scoreWord(w string, logProbs [26][26]float64) (float64, bool) {
	if len(w) < 2 {
		return 0, false
	}
	sum := 0.0
	for i := 0; i < len(w)-1; i++ {
		a, b := w[i]-'a', w[i+1]-'a'
		sum += logProbs[a][b]
	}
	return sum / float64(len(w)-1), true
}

var genTmpl = template.Must(template.New("").Funcs(template.FuncMap{
	"fmtf": func(f float64) string { return fmt.Sprintf("%.6f", f) },
}).Parse(`// Code generated by cmd/gen/ngrams. DO NOT EDIT.
// Source: dwyl/english-words words_alpha.txt ({{.WordCount}} words, {{.Date}})
// Refresh: make gen-ngrams
package scorer

import "math"

// bigramLogProb[i][j] = log P(char(j+97) | char(i+97)) in English words corpus.
// Indices: 'a'=0, 'b'=1, ..., 'z'=25. Laplace-smoothed.
var bigramLogProb = [26][26]float64{
{{- range $i, $row := .LogProbs}}
	{ {{- range $j, $v := $row}}{{if $j}}, {{end}}{{fmtf $v}}{{end}} }, // {{index $.Letters $i}}
{{- end}}
}

// ngramScoreMin and ngramScoreMax are the 5th/95th percentile of per-word
// average bigram log-prob on the training corpus, used for normalization.
const ngramScoreMin = {{fmtf .Min}}
const ngramScoreMax = {{fmtf .Max}}

// ngramBrandability scores how English-phonotactically natural an SLD is.
// Returns [0.1, 1.0]: real words and well-coined names score high; consonant
// clusters like "xkqvz" score near the floor.
func ngramBrandability(sld string) float64 {
	n := len(sld)
	if n < 2 {
		return 0.5
	}
	sum := 0.0
	for i := 0; i < n-1; i++ {
		a := sld[i] - 'a'
		b := sld[i+1] - 'a'
		if a > 25 || b > 25 {
			return 0.2 // non-alpha character
		}
		sum += bigramLogProb[a][b]
	}
	avg := sum / float64(n-1)
	v := (avg - ngramScoreMin) / (ngramScoreMax - ngramScoreMin)
	return math.Max(0.1, math.Min(1.0, v))
}
`))

func writeGenFile(path string, logProbs [26][26]float64, min5, max95 float64, wordCount int) error {
	f, err := os.Create(path)
	if err != nil {
		return err
	}
	defer f.Close()

	letters := make([]string, 26)
	for i := range letters {
		letters[i] = string(rune('a' + i))
	}

	rows := make([][26]float64, 26)
	for i := range rows {
		rows[i] = logProbs[i]
	}

	return genTmpl.Execute(f, struct {
		Date      string
		WordCount int
		LogProbs  [][26]float64
		Letters   []string
		Min       float64
		Max       float64
	}{
		Date:      time.Now().UTC().Format("2006-01-02"),
		WordCount: wordCount,
		LogProbs:  rows,
		Letters:   letters,
		Min:       min5,
		Max:       max95,
	})
}
